// Busca rápida por id (ex.: PLACES_BY_ID['BR'])
export const PLACES_BY_ID: Record<string, Place> = Object.fromEntries(
  PLACES.map((p) => [p.id, p]),
)

// Parte que vai entre parênteses: país a que pertence e/ou observação.
// Ex.: "França" ou "Reino Unido; reivindicadas pela Argentina"
export function placeDetail(place: Place): string {
  const parts: string[] = []
  if (place.parent) parts.push(PLACES_BY_ID[place.parent].name)
  if (place.note) parts.push(place.note)
  return parts.join('; ')
}

// Nome completo mostrado no balão: "Guiana Francesa (França)"
export function placeLabel(place: Place): string {
  const detail = placeDetail(place)
  return detail ? `${place.name} (${detail})` : place.name
}